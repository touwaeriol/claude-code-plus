export type ToolPermissionRequest = {
  toolName: string
  input: unknown
  toolUseId?: string
  permissionSuggestions?: unknown[]
  blockedPath?: string
}

export type ToolPermissionResult = {
  approved: boolean
  denyReason?: string
  /** Snapshot metadata to inject into tool_result (for Write/Edit tools) */
  snapshotMeta?: {
    historyTs: number
    canRollback: boolean
    isNewFile?: boolean
    isOverwrite?: boolean
  }
}

export type ClaudeCliQueryCallbacks = {
  onJsonMessage: (msg: unknown) => void
  requestPermission: (req: ToolPermissionRequest) => Promise<ToolPermissionResult>
}

export class ClaudeCliSessionManager implements vscode.Disposable {
  private readonly sessions = new Map<string, ClaudeCliSession>()

  constructor(private readonly log?: (message: string) => void) {}

  async getOrCreate(config: ClaudeCliSessionConfig): Promise<ClaudeCliSession> {
    const existing = this.sessions.get(config.sessionId)
    if (existing && existing.matches(config)) return existing

    existing?.dispose()

    const created = new ClaudeCliSession(config, this.log)
    this.sessions.set(config.sessionId, created)
    await created.ensureStarted()
    return created
  }

  /**
   * Get an existing session by ID without creating a new one.
   * Returns undefined if no session exists with the given ID.
   */
  getSession(sessionId: string): ClaudeCliSession | undefined {
    return this.sessions.get(sessionId)
  }

  /**
   * Run a task to background for a specific session.
   * @param sessionId The session ID
   * @param taskId Optional task ID to background a specific task
   * @returns Promise with the background result
   */
  async runToBackground(sessionId: string, taskId?: string): Promise<{
    success: boolean
    isBash?: boolean
    taskId?: string
    command?: string
    bashCount?: number
    agentCount?: number
    backgroundedBashIds?: string[]
    backgroundedAgentIds?: string[]
    error?: string
  }> {
    const session = this.sessions.get(sessionId)
    if (!session) {
      return { success: false, error: `No session found with ID: ${sessionId}` }
    }
    return session.sendRunToBackground(taskId)
  }

  dispose() {
    this.sessions.forEach(s => s.dispose());
    this.sessions.clear()
  }
}

class ClaudeCliSession implements vscode.Disposable {
  private proc: ChildProcessWithoutNullStreams | undefined
  private stdoutRl: readline.Interface | undefined
  private stderrRl: readline.Interface | undefined

  private readyPromise: Promise<void> | undefined
  private readyResolve: (() => void) | undefined
  private readyReject: ((err: Error) => void) | undefined

  private disposed = false

  /** Callbacks to invoke when the session is disposed */
  private readonly closeCallbacks: (() => void)[] = []

  /** Tracks snapshot metadata by toolUseId for injecting [jb:*] markers into tool_result */
  private readonly snapshotMetaMap = new Map<string, NonNullable<ToolPermissionResult['snapshotMeta']>>()

  // --- Tool-use execution (print/stream-json mode) ---
  // In `--print --input-format=stream-json --output-format=stream-json` mode,
  // Claude Code may emit tool_use blocks and wait for the client to provide a
  // tool_result via stdin. We handle only the user-interaction MCP tool for now
  // to support interactive question popups in the webview.
  private readonly toolUseByIndex: Map<number, { id: string; name: string }> = new Map()
  private readonly toolUseStartInputById: Map<string, Record<string, unknown>> = new Map()
  private readonly toolUseInputJsonById: Map<string, string> = new Map()
  private readonly executedToolUseIds: Set<string> = new Set()
  private toolExecQueue: Promise<void> = Promise.resolve()

  private activeQuery:
    | {
        generation: number
        onJsonMessage: (msg: unknown) => void
        requestPermission: ClaudeCliQueryCallbacks['requestPermission']
        skipPermissions: boolean
        resolve: () => void
        reject: (err: Error) => void
        done: Promise<void>
      }
    | undefined

  private queryGeneration = 0

  constructor(
    private readonly config: ClaudeCliSessionConfig,
    private readonly log?: (message: string) => void
  ) {}

  private isAskUserQuestionToolName(name: string): boolean {
    if (name === 'mcp__user-interaction__AskUserQuestion') return true
    if (name === 'AskUserQuestion') return true

    if (!name.endsWith('AskUserQuestion')) return false
    const lower = name.toLowerCase()
    return lower.includes('user-interaction') || lower.includes('user_interaction')
  }

  matches(config: ClaudeCliSessionConfig): boolean {
    const addDirsMatch = 
      (this.config.addDirs ?? []).length === (config.addDirs ?? []).length &&
      (this.config.addDirs ?? []).every((d, i) => d === (config.addDirs ?? [])[i])
    
    return (
      config.sessionId === this.config.sessionId &&
      config.cwd === this.config.cwd &&
      config.model === this.config.model &&
      config.permissionMode === this.config.permissionMode &&
      config.includePartialMessages === this.config.includePartialMessages &&
      config.dangerouslySkipPermissions === this.config.dangerouslySkipPermissions &&
      config.connectId === this.config.connectId &&
      addDirsMatch
    )
  }

  async ensureStarted(): Promise<void> {
    if (this.disposed) throw new Error('Claude CLI session disposed')
    if (this.proc && !this.proc.killed) return
    if (this.readyPromise) return this.readyPromise

    this.readyPromise = new Promise<void>((resolve, reject) => {
      this.readyResolve = resolve
      this.readyReject = reject
    })

    const args = buildClaudeArgs(this.config)
    this.log?.(`[claude] spawn: claude ${args.join(' ')}`)

    this.proc = spawn('claude', args, {
      cwd: this.config.cwd || undefined,
      shell: true, // Windows installs claude as a shim; `shell` makes it resolvable
      windowsHide: true,
      env: {
        ...process.env,
        CLAUDE_CODE_ENTRYPOINT: 'vscode-extension',
      },
      stdio: ['pipe', 'pipe', 'pipe'],
    })

    // The CLI may not emit any stdout until it receives the first user message. We only need to
    // ensure the process is spawned + streams are wired up before callers can write to stdin.
    this.proc.once('spawn', () => {
      this.readyResolve?.()
      this.readyResolve = undefined
      this.readyReject = undefined
    })

    this.proc.on('error', (err) => {
      this.readyReject?.(err instanceof Error ? err : new Error(String(err)))
      this.readyReject = undefined
    })

    this.proc.on('exit', (code, signal) => {
      const msg = `Claude CLI exited code=${String(code)} signal=${String(signal)}`
      this.log?.(`[claude] ${msg}`)
      this.readyReject?.(new Error(msg))
      this.readyReject = undefined

      const q = this.activeQuery
      this.activeQuery = undefined
      q?.reject(new Error(msg))
    })

    this.stdoutRl = readline.createInterface({ input: this.proc.stdout, crlfDelay: Infinity })
    this.stdoutRl.on('line', (line) => this.onStdoutLine(line))

    this.stderrRl = readline.createInterface({ input: this.proc.stderr, crlfDelay: Infinity })
    this.stderrRl.on('line', (line) => {
      const trimmed = line.trim()
      if (!trimmed) return
      this.log?.(`[claude:stderr] ${trimmed}`)
    })

    return this.readyPromise
  }

  startQuery(prompt: string, callbacks: ClaudeCliQueryCallbacks): { cancel: () => void; done: Promise<void> } {
    const generation = ++this.queryGeneration

    const previous = this.activeQuery
    if (previous) {
      // If a query is still running, interrupt it and reject to unblock the caller.
      this.sendInterrupt()
      previous.reject(new Error('Query superseded by a new request'))
      this.activeQuery = undefined
    }

    let resolveDone: (() => void) | undefined
    let rejectDone: ((err: Error) => void) | undefined

    const done = new Promise<void>((resolve, reject) => {
      resolveDone = resolve
      rejectDone = reject
    })

    const skipPermissions = this.config.dangerouslySkipPermissions

    this.activeQuery = {
      generation,
      onJsonMessage: callbacks.onJsonMessage,
      requestPermission: callbacks.requestPermission,
      skipPermissions,
      resolve: resolveDone!,
      reject: rejectDone!,
      done,
    }

    void (async () => {
      try {
        await this.ensureStarted()
        if (!this.proc || !this.proc.stdin.writable) throw new Error('Claude CLI not writable')
        const msg = buildUserMessage(prompt, this.config.sessionId)
        this.proc.stdin.write(JSON.stringify(msg) + '\n', 'utf8')
      } catch (err) {
        const error = err instanceof Error ? err : new Error(String(err))
        this.activeQuery?.reject(error)
      }
    })()

    const cancel = () => {
      if (this.activeQuery?.generation !== generation) return
      this.sendInterrupt()
      this.activeQuery.reject(new Error('Query cancelled'))
      this.activeQuery = undefined
    }

    return { cancel, done }
  }

  /**
   * Register a callback to be invoked when the session is disposed
   */
  onClose(callback: () => void): void {
    this.closeCallbacks.push(callback)
  }

  dispose() {
    this.disposed = true
    
    // Invoke close callbacks
    for (const callback of this.closeCallbacks) {
      try {
        callback()
      } catch (e) {
        // Ignore callback errors
      }
    }
    this.closeCallbacks.length = 0
    
    try {
      this.stdoutRl?.close()
      this.stderrRl?.close()
    } catch {
      // ignore
    }
    try {
      this.proc?.kill()
    } catch {
      // ignore
    }
    this.proc = undefined
    this.stdoutRl = undefined
    this.stderrRl = undefined
    this.readyPromise = undefined
    this.readyResolve = undefined
    this.readyReject = undefined
    this.activeQuery = undefined
  }

  private onStdoutLine(raw: string) {
    const line = raw.trim()
    if (!line) return

    let parsed: any
    try {
      parsed = JSON.parse(line)
    } catch {
      // Claude --verbose logs go to stderr, but be defensive.
      this.log?.(`[claude] non-json stdout: ${line.slice(0, 200)}`)
      return
    }

    const type = typeof parsed?.type === 'string' ? parsed.type : ''

    if (type === 'system' && parsed?.subtype === 'init') {
      // The CLI sends this once and then starts streaming events.
      this.readyResolve?.()
      this.readyResolve = undefined
      this.readyReject = undefined
      return
    }

    if (type === 'control_request') {
      void this.handleControlRequest(parsed)
      return
    }

    // If Claude emits tool_use blocks, it may wait for the client to send tool_result.
    // We only auto-handle user-interaction's AskUserQuestion for now.
    void this.maybeHandleToolUse(parsed)

    // Inject [jb:*] markers into tool_result content blocks
    this.injectSnapshotMetaIntoToolResults(parsed)

    if (type === 'result') {
      const q = this.activeQuery
      if (q) {
        q.onJsonMessage(parsed)

        const currentGeneration = q.generation
        void this.toolExecQueue
          .catch(() => {
            // ignore tool execution errors here; they should already be reflected in tool_result
          })
          .finally(() => {
            if (this.activeQuery?.generation !== currentGeneration) return
            q.resolve()
            this.activeQuery = undefined
          })
      }
      return
    }

    const q = this.activeQuery
    if (q) q.onJsonMessage(parsed)
  }

  private async maybeHandleToolUse(parsed: any): Promise<void> {
    try {
      if (!parsed || typeof parsed !== 'object') return
      if (parsed.type !== 'stream_event') return

      const ev = parsed.event
      if (!ev || typeof ev !== 'object') return

      const evType = typeof ev.type === 'string' ? ev.type : ''
      const index = typeof ev.index === 'number' ? ev.index : undefined

      const getContentBlock = (): any => {
        // stream-json uses snake_case `content_block`.
        return (ev as any).content_block ?? (ev as any).contentBlock ?? (ev as any).rawContentBlock
      }

      const getDelta = (): any => {
        // stream-json uses snake_case `delta`.
        return (ev as any).delta ?? (ev as any).Delta
      }

      if (evType === 'content_block_start') {
        const block = getContentBlock()
        if (!block || typeof block !== 'object') return
        if (block.type !== 'tool_use') return

        const id = typeof block.id === 'string' ? block.id : ''
        const name = typeof block.name === 'string' ? block.name : ''
        if (!id || !name) return

        const rawInput = (block as any).input
        if (rawInput && typeof rawInput === 'object' && !Array.isArray(rawInput)) {
          this.toolUseStartInputById.set(id, rawInput as Record<string, unknown>)
        }

        if (typeof index === 'number') {
          this.toolUseByIndex.set(index, { id, name })
        }
        if (!this.toolUseInputJsonById.has(id)) {
          this.toolUseInputJsonById.set(id, '')
        }
        return
      }

      if (evType === 'content_block_delta') {
        const delta = getDelta()
        if (!delta || typeof delta !== 'object') return
        if (delta.type !== 'input_json_delta') return

        const partial =
          typeof (delta as any).partial_json === 'string'
            ? (delta as any).partial_json
            : typeof (delta as any).partialJson === 'string'
              ? (delta as any).partialJson
              : ''
        if (!partial) return

        if (typeof index !== 'number') return
        const toolUse = this.toolUseByIndex.get(index)
        if (!toolUse) return

        const prev = this.toolUseInputJsonById.get(toolUse.id) ?? ''
        this.toolUseInputJsonById.set(toolUse.id, prev + partial)
        return
      }

      if (evType !== 'content_block_stop') return

      // Note:
      // In Claude stream-json, `content_block_stop` usually does NOT include the
      // full `content_block` (only `{type,index}`), so we must be able to
      // resolve tool_use info by `index`.
      let toolUseId = ''
      let toolName = ''

      const block = getContentBlock()
      if (block && typeof block === 'object' && (block as any).type === 'tool_use') {
        toolUseId = typeof (block as any).id === 'string' ? (block as any).id : ''
        toolName = typeof (block as any).name === 'string' ? (block as any).name : ''
      }

      if ((!toolUseId || !toolName) && typeof index === 'number') {
        const toolUse = this.toolUseByIndex.get(index)
        if (toolUse) {
          toolUseId = toolUse.id
          toolName = toolUse.name
        }
      }

      if (!toolUseId || !toolName) return
      if (this.executedToolUseIds.has(toolUseId)) return

      // Only handle this specific tool for now to avoid interfering with other
      // tool execution behaviors of Claude CLI.
      if (!this.isAskUserQuestionToolName(toolName)) return

      let input: Record<string, unknown> = {}
      const startInput = this.toolUseStartInputById.get(toolUseId)
      if (startInput && typeof startInput === 'object') {
        input = startInput
      }

      // If input is empty, try to build it from input_json_delta accumulator.
      if (Object.keys(input).length === 0) {
        const json = (this.toolUseInputJsonById.get(toolUseId) ?? '').trim()
        if (json) {
          try {
            const parsedJson = JSON.parse(json)
            if (parsedJson && typeof parsedJson === 'object') {
              input = parsedJson as Record<string, unknown>
            }
          } catch {
            // ignore parse errors
          }
        }
      }

      const normalizedInput = this.normalizeAskUserQuestionInput(input)

      this.executedToolUseIds.add(toolUseId)

      // Queue tool execution to keep ordering and avoid concurrent tool prompts.
      this.toolExecQueue = this.toolExecQueue.then(async () => {
        await this.executeAskUserQuestionTool(toolUseId, toolName, normalizedInput)
      })

      await this.toolExecQueue
    } catch {
      // ignore
    }
  }

  private normalizeAskUserQuestionInput(input: Record<string, unknown>): { questions: any[] } {
    const normalizeOptions = (raw: unknown): Array<{ label: string; description?: string }> => {
      if (!Array.isArray(raw)) return []
      const out: Array<{ label: string; description?: string }> = []
      for (const item of raw) {
        if (typeof item === 'string') {
          out.push({ label: item })
          continue
        }
        if (!item || typeof item !== 'object') continue
        const label = typeof (item as any).label === 'string' ? (item as any).label : ''
        if (!label) continue
        const description = typeof (item as any).description === 'string' ? (item as any).description : undefined
        out.push(description ? { label, description } : { label })
      }
      return out
    }

    const normalizeQuestion = (raw: unknown, idx: number): any | undefined => {
      if (!raw) return undefined
      if (typeof raw === 'string') {
        return {
          header: `Question ${idx + 1}`,
          question: raw,
          options: [],
          multiSelect: false,
        }
      }

      if (typeof raw !== 'object') return undefined
      const question =
        typeof (raw as any).question === 'string'
          ? (raw as any).question
          : typeof (raw as any).prompt === 'string'
            ? (raw as any).prompt
            : typeof (raw as any).text === 'string'
              ? (raw as any).text
              : ''
      if (!question) return undefined

      const header = typeof (raw as any).header === 'string' && (raw as any).header ? (raw as any).header : `Question ${idx + 1}`
      const multiSelect = typeof (raw as any).multiSelect === 'boolean' ? (raw as any).multiSelect : false
      const options = normalizeOptions((raw as any).options ?? (raw as any).choices)

      return { header, question, options, multiSelect }
    }

    // Preferred shape: { questions: [...] }
    if (Array.isArray((input as any).questions)) {
      const questions = ((input as any).questions as unknown[])
        .map((q, idx) => normalizeQuestion(q, idx))
        .filter(Boolean)
      if (questions.length > 0) return { questions }
    }

    // Common single-question shapes.
    const singleQuestionText =
      typeof (input as any).question === 'string'
        ? (input as any).question
        : typeof (input as any).prompt === 'string'
          ? (input as any).prompt
          : typeof (input as any).text === 'string'
            ? (input as any).text
            : ''

    if (singleQuestionText) {
      const header = typeof (input as any).header === 'string' && (input as any).header ? (input as any).header : 'Question'
      const multiSelect = typeof (input as any).multiSelect === 'boolean' ? (input as any).multiSelect : false
      const options = normalizeOptions((input as any).options ?? (input as any).choices)
      return { questions: [{ header, question: singleQuestionText, options, multiSelect }] }
    }

    // Fallback: keep the flow unblocked by always producing a valid schema.
    const fallbackText = (() => {
      try {
        const s = JSON.stringify(input)
        return s && s !== '{}' ? s : 'Please provide your answer.'
      } catch {
        return 'Please provide your answer.'
      }
    })()

    return { questions: [{ header: 'Question', question: fallbackText, options: [], multiSelect: false }] }
  }

  private async executeAskUserQuestionTool(
    toolUseId: string,
    toolName: string,
    input: { questions: any[] }
  ): Promise<void> {
    if (!this.proc || !this.proc.stdin.writable) return

    // Guard: tool execution only makes sense while a query is active.
    if (!this.activeQuery) return

    this.log?.(`[claude] auto-run tool_use: tool_use_id=${toolUseId} tool=${toolName}`)

    let toolResultText = ''
    let isError = false

    try {
      const server = await this.getBuiltinMcpServer('user-interaction')
      if (!server) {
        throw new Error("Built-in MCP server 'user-interaction' not found")
      }

      const result = await this.callServerTool(server, 'AskUserQuestion', input as any, toolUseId)
      isError = Boolean(result?.isError)

      const content = result?.content
      if (typeof content === 'string') {
        toolResultText = content
      } else if (Array.isArray(content)) {
        toolResultText = (content as any[])
          .filter((item: any) => item && typeof item === 'object' && item.type === 'text')
          .map((item: any) => String(item.text ?? ''))
          .filter(Boolean)
          .join('\n')
      } else if (content != null) {
        toolResultText = JSON.stringify(content)
      }

      if (!toolResultText) {
        toolResultText = isError ? 'Tool returned empty error result' : 'OK'
      }
    } catch (e) {
      isError = true
      toolResultText = `Error: ${e instanceof Error ? e.message : String(e)}`
    }

    const msg = buildToolResultMessage(toolResultText, this.config.sessionId, toolUseId, isError)
    try {
      this.proc.stdin.write(JSON.stringify(msg) + '\n', 'utf8')
      this.log?.(`[claude] tool_result sent: tool_use_id=${toolUseId} is_error=${String(isError)}`)

      const q = this.activeQuery
      if (q) {
        q.onJsonMessage(msg)
      }
    } catch {
      // ignore
    }

    // Best-effort cleanup.
    this.toolUseStartInputById.delete(toolUseId)
    this.toolUseInputJsonById.delete(toolUseId)
  }

  /**
   * Injects [jb:*] markers into tool_result content blocks.
   * Mutates the parsed object in place.
   */
  private injectSnapshotMetaIntoToolResults(parsed: any): void {
    if (!parsed || typeof parsed !== 'object') return

    // Handle assistant message with content array
    // Format: { "type": "assistant", "message": { "content": [...] } }
    if (parsed.type === 'assistant' && Array.isArray(parsed.message?.content)) {
      for (const block of parsed.message.content) {
        this.injectMetaIntoToolResultBlock(block)
      }
    }

    // Handle stream_event with content_block_delta
    // Format: { "type": "stream_event", "event": { "type": "content_block_delta", "delta": { "type": "tool_result", ... } } }
    if (parsed.type === 'stream_event' && parsed.event?.type === 'content_block_delta') {
      const delta = parsed.event?.delta
      if (delta) {
        this.injectMetaIntoToolResultBlock(delta)
      }
    }

    // Handle result message with content array
    // Format: { "type": "result", "result": { "content": [...] } }
    if (parsed.type === 'result' && Array.isArray(parsed.result?.content)) {
      for (const block of parsed.result.content) {
        this.injectMetaIntoToolResultBlock(block)
      }
    }
  }

  /**
   * Injects [jb:*] markers into a single tool_result block if snapshot metadata exists.
   * Mutates the block in place.
   */
  private injectMetaIntoToolResultBlock(block: any): void {
    if (!block || typeof block !== 'object') return
    if (block.type !== 'tool_result') return

    const toolUseId = block.tool_use_id
    if (typeof toolUseId !== 'string') return

    const meta = this.snapshotMetaMap.get(toolUseId)
    if (!meta) return

    // Build the [jb:*] marker prefix
    const markers = [
      `[jb:historyTs=${meta.historyTs}]`,
      `[jb:isOverwrite=${meta.isOverwrite ?? false}]`,
      `[jb:isNewFile=${meta.isNewFile ?? false}]`,
      `[jb:canRollback=${meta.canRollback}]`,
    ].join('\n')

    // Inject markers at the beginning of content
    if (typeof block.content === 'string') {
      block.content = markers + '\n' + block.content
    } else if (block.content === undefined || block.content === null) {
      block.content = markers
    }
    // If content is an array or other type, we don't inject (uncommon case)

    // Remove the entry from the map after injection
    this.snapshotMetaMap.delete(toolUseId)
    this.log?.(`[claude] Injected snapshot meta for tool_use_id=${toolUseId}`)
  }

  private async handleControlRequest(parsed: any): Promise<void> {
    const requestId = typeof parsed?.request_id === 'string' ? parsed.request_id : ''
    const request = parsed?.request
    const subtype = typeof request?.subtype === 'string' ? request.subtype : ''

    if (!requestId) return

    const q = this.activeQuery

    try {
      switch (subtype) {
        case 'can_use_tool': {
          const toolName = typeof request?.tool_name === 'string' ? request.tool_name : ''
          const input = request?.input
          const toolUseId = typeof request?.tool_use_id === 'string' ? request.tool_use_id : undefined
          const suggestions = Array.isArray(request?.permission_suggestions) ? request.permission_suggestions : undefined
          const blockedPath = typeof request?.blocked_path === 'string' ? request.blocked_path : undefined

          if (!toolName) {
            await this.sendControlResponse(requestId, 'error', undefined, 'Missing tool_name')
            return
          }

          if (this.isAskUserQuestionToolName(toolName)) {
            this.log?.(`[claude] auto-allow can_use_tool for ${toolName}`)
            await this.sendControlResponse(
              requestId,
              'success',
              { behavior: 'allow', updatedInput: input ?? {} },
              undefined
            )
            return
          }

          if (!q || q.skipPermissions) {
            await this.sendControlResponse(
              requestId,
              'success',
              { behavior: 'allow', updatedInput: input ?? {} },
              undefined
            )
            return
          }

          const decision = await q.requestPermission({
            toolName,
            input,
            toolUseId,
            permissionSuggestions: suggestions,
            blockedPath,
          })

          if (decision.approved) {
            // Store snapshot metadata for later injection into tool_result
            if (toolUseId && decision.snapshotMeta) {
              this.snapshotMetaMap.set(toolUseId, decision.snapshotMeta)
            }
            await this.sendControlResponse(
              requestId,
              'success',
              { behavior: 'allow', updatedInput: input ?? {} },
              undefined
            )
          } else {
            await this.sendControlResponse(
              requestId,
              'success',
              { behavior: 'deny', message: decision.denyReason || 'Denied' },
              undefined
            )
          }
          return
        }
        case 'hook_callback': {
          // Hooks are optional for now; return an empty success payload.
          await this.sendControlResponse(requestId, 'success', {}, undefined)
          return
        }
        case 'mcp_message': {
          const serverName =
            typeof request?.server_name === 'string'
              ? request.server_name
              : typeof (request as any)?.serverName === 'string'
                ? (request as any).serverName
                : ''
          const message = request?.message

          if (!serverName) {
            await this.sendControlResponse(requestId, 'error', undefined, 'Missing server_name')
            return
          }
          if (!message || typeof message !== 'object') {
            await this.sendControlResponse(requestId, 'error', undefined, 'Missing message')
            return
          }

          const method = typeof (message as any)?.method === 'string' ? (message as any).method : ''
          const msgId = Object.prototype.hasOwnProperty.call(message ?? {}, 'id') ? (message as any).id : undefined
          this.log?.(`[claude] control_request mcp_message: server=${serverName} method=${method || '(unknown)'} id=${String(msgId)}`)

          const mcpResponse = await this.handleMcpMessage(serverName, message as any)
          await this.sendControlResponse(requestId, 'success', { mcp_response: mcpResponse }, undefined)
          return
        }
        case 'interrupt': {
          // The CLI can reply with interrupt requests in some flows; acknowledge.
          await this.sendControlResponse(requestId, 'success', {}, undefined)
          return
        }
        default: {
          await this.sendControlResponse(requestId, 'error', undefined, `Unsupported control_request subtype: ${subtype}`)
          return
        }
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err)
      await this.sendControlResponse(requestId, 'error', undefined, msg)
    }
  }

  private async handleMcpMessage(serverName: string, message: any): Promise<any> {
    // JSON-RPC envelope
    const jsonrpc = typeof message?.jsonrpc === 'string' ? message.jsonrpc : '2.0'
    const id = Object.prototype.hasOwnProperty.call(message ?? {}, 'id') ? message.id : null
    const method = typeof message?.method === 'string' ? message.method : undefined
    const params = message?.params && typeof message.params === 'object' ? message.params : {}

    const mcpServer = await this.getBuiltinMcpServer(serverName)
    if (!mcpServer) {
      return {
        jsonrpc,
        id,
        error: { code: -32601, message: `Server '${serverName}' not found` },
      }
    }

    switch (method) {
      case 'initialize': {
        const impl = (mcpServer as any)?.server?._serverInfo as { name?: string; version?: string; description?: string } | undefined
        return {
          jsonrpc,
          id,
          result: {
            protocolVersion: '2024-11-05',
            capabilities: { tools: {} },
            serverInfo: {
              name: impl?.name ?? serverName,
              version: impl?.version ?? '0.0.0',
              description: impl?.description,
            },
          },
        }
      }

      case 'tools/list': {
        const tools = this.listServerTools(mcpServer)
        return { jsonrpc, id, result: { tools } }
      }

      case 'tools/call': {
        const toolName = typeof (params as any)?.name === 'string' ? (params as any).name : ''
        const args = (params as any)?.arguments && typeof (params as any).arguments === 'object' ? (params as any).arguments : {}

        if (!toolName) {
          return { jsonrpc, id, error: { code: -32602, message: 'Missing required parameter: name' } }
        }

        const result = await this.callServerTool(mcpServer, toolName, args, id)
        return { jsonrpc, id, result }
      }

      case 'notifications/initialized': {
        return { jsonrpc, result: {} }
      }

      default: {
        return {
          jsonrpc,
          id,
          error: { code: -32601, message: `Method '${String(method)}' not found` },
        }
      }
    }
  }

  private async getBuiltinMcpServer(serverName: string): Promise<SdkMcpServer | undefined> {
    const provider = mcpRegistry.getProvider(serverName)
    if (!provider) return undefined
    return provider.getServer() as unknown as SdkMcpServer
  }

  private listServerTools(server: SdkMcpServer): any[] {
    const serverAny = server as any
    const registered = serverAny?._registeredTools as Record<string, any> | undefined
    if (!registered || typeof registered !== 'object') return []

    const tools: any[] = []
    for (const [name, tool] of Object.entries(registered)) {
      if (!tool || typeof tool !== 'object') continue
      if (tool.enabled === false) continue

      const inputSchema = (() => {
        try {
          const obj = normalizeObjectSchema(tool.inputSchema)
          return obj
            ? toJsonSchemaCompat(obj, { strictUnions: true, pipeStrategy: 'input' })
            : { type: 'object', properties: {} }
        } catch {
          return { type: 'object', properties: {} }
        }
      })()

      tools.push({
        name,
        title: tool.title,
        description: tool.description ?? '',
        inputSchema,
        annotations: tool.annotations,
        execution: tool.execution,
        _meta: tool._meta,
      })
    }

    return tools
  }

  private async callServerTool(
    server: SdkMcpServer,
    toolName: string,
    args: Record<string, unknown>,
    messageId: unknown
  ): Promise<any> {
    const serverAny = server as any
    const registered = serverAny?._registeredTools as Record<string, any> | undefined
    const tool = registered?.[toolName]

    if (!tool) {
      return {
        content: [{ type: 'text', text: `Tool ${toolName} not found` }],
        isError: true,
      }
    }
    if (tool.enabled === false) {
      return {
        content: [{ type: 'text', text: `Tool ${toolName} disabled` }],
        isError: true,
      }
    }

    const handler = tool.handler
    if (typeof handler !== 'function') {
      return {
        content: [{ type: 'text', text: `Tool ${toolName} handler type not supported` }],
        isError: true,
      }
    }

    const connectId = this.config.connectId
    const requestId = typeof messageId === 'string' || typeof messageId === 'number' ? messageId : crypto.randomUUID()
    const extra: any = {
      signal: new AbortController().signal,
      requestId,
      authInfo: {
        token: 'builtin-mcp',
        clientId: 'claude-code-plus',
        scopes: [],
        extra: { connectId },
      },
      requestInfo: {
        headers: connectId ? { 'x-mcp-connect-id': connectId } : {},
      },
      sendNotification: async () => {},
      sendRequest: async () => {
        throw new Error('sendRequest is not supported in control-protocol MCP bridging')
      },
    }

    try {
      const result = await handler(args, extra)
      if (result && typeof result === 'object') {
        // Ensure backwards-compatible shape.
        if (!Array.isArray((result as any).content)) {
          ;(result as any).content = []
        }
        return result
      }
      return { content: [{ type: 'text', text: String(result ?? '') }], isError: false }
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err)
      return { content: [{ type: 'text', text: `Error: ${msg}` }], isError: true }
    }
  }

  private async sendControlResponse(
    requestId: string,
    subtype: 'success' | 'error',
    response: unknown,
    error: string | undefined
  ): Promise<void> {
    if (!this.proc || !this.proc.stdin.writable) return

    const payload: any = {
      type: 'control_response',
      response: {
        subtype,
        request_id: requestId,
      },
    }
    if (response !== undefined) payload.response.response = response
    if (error) payload.response.error = error

    this.proc.stdin.write(JSON.stringify(payload) + '\n', 'utf8')
  }

  private sendInterrupt(): void {
    if (!this.proc || !this.proc.stdin.writable) return
    const requestId = `req_${crypto.randomUUID()}`
    const payload = {
      type: 'control_request',
      request_id: requestId,
      request: { subtype: 'interrupt' },
    }
    try {
      this.proc.stdin.write(JSON.stringify(payload) + '\n', 'utf8')
    } catch {
      // ignore
    }
  }

  /**
   * Send a run_to_background control request to the CLI.
   * This moves running tasks (Bash/Agent) to background execution.
   * 
   * @param taskId Optional task ID. If provided, backgrounds specific task.
   *               If not provided, backgrounds all running tasks.
   * @returns Promise resolving to the background result
   */
  async sendRunToBackground(taskId?: string): Promise<{
    success: boolean
    isBash?: boolean
    taskId?: string
    command?: string
    bashCount?: number
    agentCount?: number
    backgroundedBashIds?: string[]
    backgroundedAgentIds?: string[]
    error?: string
  }> {
    if (!this.proc || !this.proc.stdin.writable) {
      return { success: false, error: 'Claude CLI not writable' }
    }

    const requestId = `req_${crypto.randomUUID()}`
    const request: Record<string, unknown> = { subtype: 'run_to_background' }
    if (taskId) {
      request.task_id = taskId
    }

    const payload = {
      type: 'control_request',
      request_id: requestId,
      request,
    }

    return new Promise((resolve) => {
      // Set up a one-time listener for the response
      const timeout = setTimeout(() => {
        this.log?.(`[claude] run_to_background timeout for request ${requestId}`)
        resolve({ success: false, error: 'Request timeout' })
      }, 10000) // 10 second timeout

      const originalOnStdoutLine = this.onStdoutLine.bind(this)
      
      // Temporarily intercept stdout to catch the control_response
      const interceptHandler = (line: string) => {
        const trimmed = line.trim()
        if (!trimmed) return

        try {
          const parsed = JSON.parse(trimmed)
          if (parsed.type === 'control_response' && 
              parsed.response?.request_id === requestId) {
            clearTimeout(timeout)
            
            const response = parsed.response
            if (response.subtype === 'error') {
              resolve({ success: false, error: response.error || 'Unknown error' })
              return
            }

            const responseData = response.response as Record<string, unknown> | undefined
            const mode = responseData?.mode as string | undefined
            const type = responseData?.type as string | undefined
            const returnedTaskId = responseData?.task_id as string | undefined
            const command = responseData?.command as string | undefined

            // Handle batch mode
            if (mode === 'all') {
              this.log?.('[claude] Batch background completed')
              resolve({ success: true })
              return
            }

            // Handle single task mode
            if (taskId) {
              if (type === 'bash') {
                this.log?.(`[claude] Bash backgrounded: task_id=${returnedTaskId}`)
                resolve({
                  success: true,
                  isBash: true,
                  taskId: returnedTaskId,
                  command,
                  bashCount: 1,
                  backgroundedBashIds: returnedTaskId ? [returnedTaskId] : [],
                })
              } else if (type === 'agent') {
                this.log?.(`[claude] Agent backgrounded: task_id=${returnedTaskId}`)
                resolve({
                  success: true,
                  isBash: false,
                  taskId: returnedTaskId,
                  agentCount: 1,
                  backgroundedAgentIds: returnedTaskId ? [returnedTaskId] : [],
                })
              } else {
                const error = responseData?.error as string | undefined
                resolve({
                  success: false,
                  taskId,
                  error: error || 'Unknown task type',
                })
              }
              return
            }

            // Default success
            resolve({ success: (responseData?.success as boolean) ?? true })
            return
          }
        } catch {
          // Not a JSON line or not our response, continue normal processing
        }
        
        // Call original handler for non-control-response messages
        originalOnStdoutLine(line)
      }

      // Temporarily replace the line handler
      if (this.stdoutRl) {
        this.stdoutRl.removeAllListeners('line')
        this.stdoutRl.on('line', interceptHandler)
        
        // Restore original handler after timeout or response
        const cleanup = () => {
          if (this.stdoutRl) {
            this.stdoutRl.removeAllListeners('line')
            this.stdoutRl.on('line', (line) => this.onStdoutLine(line))
          }
        }
        
        setTimeout(cleanup, 10100) // Cleanup slightly after timeout
      }

      try {
        this.log?.(`[claude] Sending run_to_background: task_id=${taskId || 'batch'}`)
        this.proc!.stdin.write(JSON.stringify(payload) + '\n', 'utf8')
      } catch (e) {
        clearTimeout(timeout)
        resolve({ success: false, error: e instanceof Error ? e.message : String(e) })
      }
    })
  }
}

function buildUserMessage(text: string, sessionId: string) {
  return {
    type: 'user',
    message: { role: 'user', content: text },
    parent_tool_use_id: null,
    session_id: sessionId,
  }
}

function buildToolResultMessage(content: string, sessionId: string, toolUseId: string, isError: boolean) {
  return {
    type: 'user',
    message: {
      role: 'user',
      content: [
        {
          type: 'tool_result',
          tool_use_id: toolUseId,
          content,
          is_error: isError,
        },
      ],
    },
    parent_tool_use_id: toolUseId,
    session_id: sessionId,
  }
}

function buildClaudeArgs(config: ClaudeCliSessionConfig): string[] {
  const model = sanitizeCliArg(config.model, 'model')
  const sessionId = sanitizeCliArg(config.sessionId, 'sessionId')
  const permissionMode = sanitizeCliArg(config.permissionMode, 'permissionMode')

  const args = [
    '--print',
    '--verbose',
    '--output-format',
    'stream-json',
    '--input-format',
    'stream-json',
    '--session-id',
    sessionId,
    '--model',
    model,
    '--permission-mode',
    permissionMode,
  ]

  if (config.includePartialMessages) {
    args.push('--include-partial-messages')
  }

  if (config.dangerouslySkipPermissions) {
    args.push('--dangerously-skip-permissions')
  }

  // Additional directories for multi-root workspace
  if (config.addDirs && config.addDirs.length > 0) {
    for (const dir of config.addDirs) {
      args.push('--add-dir', dir)
    }
  }

  // MCP configuration file (contains server definitions)
  if (config.mcpConfigFilePath) {
    args.push('--mcp-config', config.mcpConfigFilePath)
  }

  // System prompt appendix file (contains MCP instructions)
  if (config.appendSystemPromptFilePath) {
    args.push('--append-system-prompt-file', config.appendSystemPromptFilePath)
  }

  return args
}

function sanitizeCliArg(value: string, name: string): string {
  const v = String(value || '').trim()
  if (!v) throw new Error(`Invalid Claude CLI arg: ${name} is empty`)
  // Keep this conservative since we spawn with `shell: true` on Windows.
  if (!/^[A-Za-z0-9._:-]+$/.test(v)) {
    throw new Error(`Invalid Claude CLI arg: ${name} contains unsupported characters`)
  }
  return v
}
